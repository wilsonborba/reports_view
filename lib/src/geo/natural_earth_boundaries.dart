/// Resolves an ISO 3166-1 (alpha-2 or alpha-3) or ISO 3166-2 region code to its bundled Natural Earth boundary.
GeoBoundary? lookupGeoBoundary(String rawCode) {
  final code = rawCode.trim().toUpperCase();
  if (code.isEmpty) return null;
  for (final r in naturalEarthAdmin1) {
    if (r.isoCode == code) return r;
  }
  for (final c in naturalEarthAdmin0) {
    if (c.isoCode == code || c.isoAlpha3 == code) return c;
  }
  return null;
}
