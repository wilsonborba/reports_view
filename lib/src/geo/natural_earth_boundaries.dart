/// Geographic boundary polygon(s) joined by ISO 3166-1 / ISO 3166-2 code.
class GeoBoundary {
  final String isoCode;
  final String? isoAlpha3;
  final String name;
  final String? parentCountry;
  final double centroidLon;
  final double centroidLat;
  final List<List<double>> _ringsRaw;

  const GeoBoundary({
    required this.isoCode,
    this.isoAlpha3,
    required this.name,
    this.parentCountry,
    required this.centroidLon,
    required this.centroidLat,
    required List<List<double>> rings,
  }) : _ringsRaw = rings;

  /// Decodes interleaved `[lon, lat, ...]` rings into geographic offsets `(lon, lat)`.
  Iterable<List<Offset>> get rings sync* {
    for (final raw in _ringsRaw) {
      final pts = <Offset>[];
      for (var i = 0; i + 1 < raw.length; i += 2) {
        pts.add(Offset(raw[i], raw[i + 1]));
      }
      if (pts.length >= 3) yield pts;
    }
  }
}

